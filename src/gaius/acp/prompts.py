def build_system_prompt(
    mode: WorkflowMode,
    github_repo: str = "zndx/gaius-acp",
    cadence: CadencePolicy | None = None,
) -> str:
    """Build the complete system prompt for Claude Code.

    Args:
        mode: Operating mode (observe, intervene, report)
        github_repo: GitHub repository for issue tracking
        cadence: Cadence policy for remediation controls

    Returns:
        Complete system prompt string
    """
    cadence = cadence or DEFAULT_CADENCE

    # Format role prompt with cadence values
    role = SYSTEM_PROMPT_ROLE.format(
        max_restarts_per_hour=cadence.max_restarts_per_hour,
        min_interval_between_restarts=cadence.min_interval_between_restarts,
        cooldown_after_failure=cadence.cooldown_after_failure,
        observation_window=cadence.observation_window,
        max_issues_per_day=cadence.max_issues_per_day,
        dev_branch_prefix=cadence.dev_branch_prefix,
        github_repo=github_repo,
        issue_number="{issue_number}",  # Placeholder for actual issue
    )

    # Add mode-specific prompt
    if mode == WorkflowMode.OBSERVE:
        mode_prompt = SYSTEM_PROMPT_OBSERVE.format(
            observation_window=cadence.observation_window,
        )
    elif mode == WorkflowMode.INTERVENE:
        mode_prompt = SYSTEM_PROMPT_INTERVENE
    else:
        mode_prompt = SYSTEM_PROMPT_REPORT

    return f"{role}\n\n---\n\n{mode_prompt}"


def build_incident_prompt(
    incident: dict[str, Any],
    mode: WorkflowMode,
    last_report: dict[str, Any] | None = None,
    history: list[dict[str, Any]] | None = None,
) -> str:
    """Build the incident-specific prompt for Claude Code.

    Args:
        incident: Incident data from HealthIncident.to_dict()
        mode: Operating mode
        last_report: Most recent health report summary
        history: Previous remediation attempts for this incident

    Returns:
        Incident prompt string
    """
    # Basic incident info
    prompt = f"""## Health Incident

**Fingerprint**: `{incident['fingerprint']}`
**Endpoint**: `{incident['endpoint']}`
**Failure Mode**: `{incident['failure_mode_id']}`
**RPN Score**: {incident['rpn']['rpn']} (S:{incident['rpn']['severity']} × O:{incident['rpn']['occurrence']} × D:{incident['rpn']['detection']})
**Current Tier**: Tier {incident['current_tier']}
**Status**: {incident['status']}
**Attempts**: {incident['attempts']}
**Created**: {incident['created_at']}
"""

    # Add GitHub issue if linked
    if incident.get('github_issue'):
        prompt += f"**GitHub Issue**: #{incident['github_issue']}\n"

    # Add last health report if available
    if last_report:
        prompt += f"""
### Recent Health Report

- **Healthy**: {last_report.get('healthy', 'unknown')}
- **Summary**: {last_report.get('summary', 'N/A')}
- **Passed**: {last_report.get('passed', 0)} | **Warnings**: {last_report.get('warnings', 0)} | **Failures**: {last_report.get('failures', 0)}
"""

    # Add remediation history if available
    if history:
        prompt += "\n### Remediation History\n\n"
        for attempt in history[-5:]:  # Last 5 attempts
            prompt += f"- **{attempt.get('timestamp', 'unknown')}**: {attempt.get('action', 'unknown')} → {attempt.get('outcome', 'unknown')}\n"

    # Add mode-specific instructions
    if mode == WorkflowMode.OBSERVE:
        prompt += """
### Your Task

1. Use MCP tools to gather diagnostic information
2. Identify the root cause
3. Document your findings
4. Recommend next steps (but do not execute)
"""
    elif mode == WorkflowMode.INTERVENE:
        prompt += """
### Your Task

1. Verify the diagnosis
2. Execute appropriate remediation
3. Verify recovery with health check
4. Document the outcome
"""
    else:
        prompt += """
### Your Task

Generate a summary report of this incident and the current system state.
"""

    return prompt


